// @depends-on src/flags/**
/**
 * Writes src/flags/ (the flags, and the module that holds them all) from scripts/flags/spec.ts. Run
 * after editing a spec:
 *
 *   bun run build:flags
 *
 * tests/scripts/flags.test.ts fails when the written files are stale.
 * `--coverage` prints how many of the listed regions the spec draws, and how
 * many of those need a hand-authored path.
 */
import { writeFileSync } from "node:fs";
import { ALIAS, EMBLEM, HELD, PARAMETRIC } from "./flags/coverage";
import { REGIONS } from "./flags/regions";
import { SPEC } from "./flags/spec";
import { compileFlag } from "./lib/flags";

const OUT = new URL("../src/flags/", import.meta.url);

const header =
  "// Generated by scripts/build-flags.ts from scripts/flags/spec.ts. Do not edit.\n";

export function flagFiles(): {
  js: string;
  dts: string;
  allJs: string;
  allDts: string;
  stats: Stats;
} {
  const codes = Object.keys(SPEC).sort();
  const stats: Stats = { drawn: codes.length, escape: [], kinds: new Map() };
  const js: string[] = [header];
  const dts: string[] = [
    header,
    `/** A flag: its ISO 3166-1 code and the inner markup of a \`0 0 32 24\` SVG. */
export interface FlagData {
  readonly code: string;
  readonly body: string;
}
`,
  ];
  for (const code of codes) {
    if (!REGIONS.includes(code)) throw new Error(`${code} is not a region`);
    const { body, kinds, freehand } = compileFlag(SPEC[code], (c) => SPEC[c]);
    if (freehand) stats.escape.push(code);
    for (const kind of kinds) {
      stats.kinds.set(kind, (stats.kinds.get(kind) ?? 0) + 1);
    }
    js.push(`export const ${code} = { code: "${code}", body: '${body}' };\n`);
    dts.push(`export const ${code}: FlagData;\n`);
  }
  const list = codes.join(", ");
  const allJs = `${header}// Every flag in one module: \`carbon-components-svelte/flags/all\`. Importing it
// puts all of them in the bundle. Import single flags from
// \`carbon-components-svelte/flags\` to keep the rest out.
import { ${list} } from "./index.js";

export const flags = { ${list} };

/**
 * The flag for an ISO 3166-1 code, or \`undefined\` for a region with none
 * drawn yet. The code is matched in upper case, and no name on
 * \`Object.prototype\` has an upper case spelling, so a stray key finds nothing.
 * @param {string} code
 * @returns {import("./index.js").FlagData | undefined}
 */
export function getFlag(code) {
  return /** @type {Record<string, import("./index.js").FlagData | undefined>} */ (
    flags
  )[code.toUpperCase()];
}
`;
  const allDts = `${header}import type { FlagData } from "./index.js";

export const flags: {
${codes.map((code) => `  readonly ${code}: FlagData;`).join("\n")}
};

/**
 * The flag for an ISO 3166-1 code, or \`undefined\` for a region with none
 * drawn yet.
 */
export function getFlag(code: string): FlagData | undefined;
`;
  return { js: js.join(""), dts: dts.join(""), allJs, allDts, stats };
}

type Stats = {
  drawn: number;
  escape: string[];
  kinds: Map<string, number>;
};

if (import.meta.main) {
  const { js, dts, allJs, allDts, stats } = flagFiles();
  writeFileSync(new URL("index.js", OUT), js);
  writeFileSync(new URL("index.d.ts", OUT), dts);
  writeFileSync(new URL("all.js", OUT), allJs);
  writeFileSync(new URL("all.d.ts", OUT), allDts);
  console.log(
    `[build-flags] ${stats.drawn} flags, ${js.length} B of source, ${stats.escape.length} with a hand-authored path (${stats.escape.join(" ")})`,
  );
  if (process.argv.includes("--coverage")) {
    const total = REGIONS.length;
    const plain = stats.drawn - stats.escape.length;
    const free = plain + PARAMETRIC.length + Object.keys(ALIAS).length;
    const pct = (n: number) => `${((n / total) * 100).toFixed(1)}%`;
    console.log(`drawn ${stats.drawn} of ${total}`);
    console.log(
      `no hand-authored path: ${free} (${pct(free)}) = ${plain} drawn + ${PARAMETRIC.length} parametric + ${Object.keys(ALIAS).length} alias`,
    );
    console.log(
      `needs an emblem path: ${EMBLEM.length + stats.escape.length} (${pct(EMBLEM.length + stats.escape.length)}); held: ${HELD.length} (${pct(HELD.length)})`,
    );
    console.log(
      [...stats.kinds].map(([kind, count]) => `${kind}: ${count}`).join(", "),
    );
  }
}
