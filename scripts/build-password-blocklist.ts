/**
 * Writes src/PasswordStrength/common-passwords.js (the top 1,000) and
 * common-passwords-10k.js (the top 1,000 plus ranks 1,001 to 10,000) from a
 * rank-ordered word list, one word per line. The shipped lists come from
 * SecLists `Passwords/Common-Credentials/10k-most-common.txt` (MIT).
 *
 *   bun scripts/build-password-blocklist.ts /path/to/10k-most-common.txt
 */
import { $ } from "bun";
import { encodeTier } from "../src/PasswordStrength/blocklist.js";

const input = process.argv[2];
if (!input) throw new Error("Pass the path of the ranked word list.");

const words = (await Bun.file(input).text())
  .split("\n")
  .map((w) => w.trim().toLowerCase())
  .filter(Boolean);
const unique = [...new Set(words)];

const tier = (upTo: number, from: number, to: number) =>
  `{ upTo: ${upTo}, words: ${JSON.stringify(encodeTier(unique.slice(from, to)))} }`;

const header = (what: string) => `// @ts-check
// ${what}
// Source: SecLists Passwords/Common-Credentials/10k-most-common.txt (MIT).
// Generated by scripts/build-password-blocklist.ts; do not edit.
`;

await Bun.write(
  "src/PasswordStrength/common-passwords.js",
  `${header("The 1,000 most common passwords, front-coded in three rank tiers.")}
/** @type {import("./blocklist.js").BlocklistTier[]} */
export const commonPasswords = [
  ${tier(10, 0, 10)},
  ${tier(100, 10, 100)},
  ${tier(1000, 100, 1000)},
];
`,
);
await Bun.write(
  "src/PasswordStrength/common-passwords-10k.js",
  `${header("The 10,000 most common passwords: the top 1,000 plus ranks 1,001 to 10,000.")}
import { commonPasswords } from "./common-passwords.js";

/** @type {import("./blocklist.js").BlocklistTier[]} */
export const commonPasswords10k = [
  ...commonPasswords,
  ${tier(10000, 1000, 10000)},
];
`,
);
await $`bun fmt src/PasswordStrength`.quiet();
console.log(`wrote ${unique.length} words`);
