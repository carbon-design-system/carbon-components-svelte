/**
 * Builds the Tailwind preset, the Tailwind v4 theme, and the DTCG JSON from
 * the same `TokenData` as the `carbon-components-svelte/tokens` module, so
 * the css tests can rebuild each one from their cached compile and compare.
 *
 * Tailwind colors read `var(--cds-*)`, so a utility follows the theme,
 * `ThemeZone` and `Layer` that `all.css` sets. Type, spacing and size
 * values are literals: they don't change with the theme.
 */
import { THEMES, type TokenData } from "./tokens";

type Theme = (typeof THEMES)[number];

/**
 * Color groups whose utility is the token name: `text-primary` for
 * `text-text-primary`, `border-subtle` for `border-border-subtle`. Tailwind
 * v3 and v4 both prefer these over `colors`, so `border-interactive` reads
 * `border-interactive`, not `interactive`.
 */
const SHORTHANDS = { textColor: "text-", borderColor: "border-" } as const;

/** DTCG and Style Dictionary dimensions take `px` and `rem` only. */
const DIMENSION = /^-?[\d.]+(px|rem)$/;
const HEX = /^#([\da-f]{3,8})$/i;
const RGB = /^rgba?\(([^)]+)\)$/i;
const RGB_SEPARATOR = /[\s,/]+/;
const ALIAS = /^var\(--cds-([\w-]+)\)$/;
const QUOTES = /^['"]|['"]$/g;

const HEADER = "Generated by scripts/build-tokens.ts from css/all.scss.";

type FontSize = [
  string,
  { lineHeight?: string; letterSpacing?: string; fontWeight?: string },
];

export type TailwindTheme = {
  colors: Record<string, string>;
  textColor: Record<string, string>;
  borderColor: Record<string, string>;
  spacing: Record<string, string>;
  fontSize: Record<string, FontSize>;
};

function colorNames(data: TokenData): string[] {
  return [...Object.keys(data.color), ...Object.keys(data.component)];
}

function shorthand(data: TokenData, prefix: string): Record<string, string> {
  return Object.fromEntries(
    Object.keys(data.color)
      .filter((name) => name.startsWith(prefix))
      .map((name) => [name.slice(prefix.length), `var(--cds-${name})`]),
  );
}

/** The `theme.extend` of the Tailwind v3 preset. */
export function tailwindTheme(data: TokenData): TailwindTheme {
  const fontSize: Record<string, FontSize> = {};
  for (const [name, style] of Object.entries(data.type)) {
    const options: FontSize[1] = {};
    if (style["line-height"]) options.lineHeight = style["line-height"];
    if (style["letter-spacing"]) {
      options.letterSpacing = style["letter-spacing"];
    }
    if (style["font-weight"]) options.fontWeight = style["font-weight"];
    fontSize[name] = [style["font-size"] ?? "", options];
  }

  return {
    colors: Object.fromEntries(
      colorNames(data).map((name) => [name, `var(--cds-${name})`]),
    ),
    textColor: shorthand(data, SHORTHANDS.textColor),
    borderColor: shorthand(data, SHORTHANDS.borderColor),
    spacing: { ...data.spacing, ...data.size },
    fontSize,
  };
}

/** `src/tokens/tailwind.js` and its declarations. */
export function renderTailwindPreset(data: TokenData): {
  js: string;
  dts: string;
} {
  const json = JSON.stringify(tailwindTheme(data), null, 2);

  const js = `// ${HEADER} Do not edit.

/**
 * Tailwind CSS v3 preset with Carbon v11 colors, spacing, and type styles.
 * Colors read \`var(--cds-*)\`, so import \`carbon-components-svelte/css/all.css\`.
 */
export default {
  theme: {
    extend: ${json},
  },
};
`;

  const keys = (record: Record<string, unknown>) =>
    Object.keys(record)
      .map((name) => JSON.stringify(name))
      .join(" | ");
  const theme = tailwindTheme(data);

  const dts = `// ${HEADER} Do not edit.

type FontSize = [
  fontSize: string,
  options: { lineHeight?: string; letterSpacing?: string; fontWeight?: string },
];

/**
 * Tailwind CSS v3 preset with Carbon v11 colors, spacing, and type styles.
 * Colors read \`var(--cds-*)\`, so import \`carbon-components-svelte/css/all.css\`.
 */
declare const preset: {
  theme: {
    extend: {
      colors: Record<${keys(theme.colors)}, string>;
      textColor: Record<${keys(theme.textColor)}, string>;
      borderColor: Record<${keys(theme.borderColor)}, string>;
      spacing: Record<${keys(theme.spacing)}, string>;
      fontSize: Record<${keys(theme.fontSize)}, FontSize>;
    };
  };
};

export default preset;
`;

  return { js, dts };
}

/** `src/tokens/tailwind.css`, the Tailwind CSS v4 theme. */
export function renderTailwindCss(data: TokenData): string {
  const theme = tailwindTheme(data);
  const lines = (prefix: string, record: Record<string, string>) =>
    Object.entries(record).map(
      ([name, value]) => `  --${prefix}-${name}: ${value};`,
    );

  const type = Object.entries(theme.fontSize).flatMap(
    ([name, [size, options]]) => [
      `  --text-${name}: ${size};`,
      ...(options.lineHeight
        ? [`  --text-${name}--line-height: ${options.lineHeight};`]
        : []),
      ...(options.letterSpacing
        ? [`  --text-${name}--letter-spacing: ${options.letterSpacing};`]
        : []),
      ...(options.fontWeight
        ? [`  --text-${name}--font-weight: ${options.fontWeight};`]
        : []),
    ],
  );

  return `/* ${HEADER} Do not edit. */

/*
 * Tailwind CSS v4 theme with Carbon v11 colors, spacing, and type styles.
 * Colors read var(--cds-*), so import carbon-components-svelte/css/all.css.
 * "inline" makes utilities read var(--cds-*) where they apply, so they
 * follow Theme, ThemeZone, and Layer.
 */
@theme inline {
${[
  ...lines("color", theme.colors),
  ...lines("text-color", theme.textColor),
  ...lines("border-color", theme.borderColor),
].join("\n")}
}

@theme {
${[...lines("spacing", theme.spacing), ...type].join("\n")}
}
`;
}

type DtcgToken = {
  $type: string;
  $value: unknown;
};

/** `#rrggbb` or `#rrggbbaa`, the color form DTCG tools read. */
export function toHex(value: string): string {
  const hex = value.match(HEX)?.[1];
  if (hex) {
    const full =
      hex.length <= 4 ? [...hex].map((digit) => digit + digit).join("") : hex;
    return `#${full.toLowerCase()}`;
  }

  const rgb = value.match(RGB)?.[1];
  if (!rgb) throw new Error(`Unsupported color: ${value}`);

  const parts = rgb.split(RGB_SEPARATOR).filter(Boolean);
  const channel = (part: string) =>
    part.endsWith("%")
      ? Math.round((Number.parseFloat(part) / 100) * 255)
      : Math.round(Number.parseFloat(part));
  const alpha = parts[3] === undefined ? 1 : Number.parseFloat(parts[3]);
  const bytes = parts.slice(0, 3).map(channel);
  if (alpha < 1) bytes.push(Math.round(alpha * 255));

  return `#${bytes.map((byte) => byte.toString(16).padStart(2, "0")).join("")}`;
}

/** A `var(--cds-name)` value becomes the alias `{name}`. */
function colorValue(value: string): string {
  const alias = value.match(ALIAS)?.[1];
  return alias ? `{${alias}}` : toHex(value);
}

function dimension(value: string): string {
  return value === "0" ? "0px" : value;
}

function typography(style: TokenData["type"][string]): DtcgToken {
  const value: Record<string, unknown> = {};
  const family = style["font-family"];
  if (family) {
    value.fontFamily = family
      .split(",")
      .map((name) => name.trim().replace(QUOTES, ""));
  }
  if (style["font-size"]) value.fontSize = style["font-size"];
  if (style["font-weight"]) {
    value.fontWeight = Number.parseInt(style["font-weight"], 10);
  }
  if (style["line-height"]) {
    value.lineHeight = Number.parseFloat(style["line-height"]);
  }
  if (style["letter-spacing"]) {
    value.letterSpacing = dimension(style["letter-spacing"]);
  }
  return { $type: "typography", $value: value };
}

const THEME_NAMES: Record<Theme, string> = {
  white: "White",
  g10: "Gray 10",
  g80: "Gray 80",
  g90: "Gray 90",
  g100: "Gray 100",
};

/**
 * The DTCG document. Each top-level key is a token set, as in Tokens
 * Studio's single-file format: `core` holds type, spacing, and sizes, and
 * one set per theme holds its colors. `$themes` pairs `core` with each
 * theme set. Token names are Carbon's, so a `cds` prefix gives the same
 * `--cds-*` names as `all.css`.
 */
export function dtcgTokens(data: TokenData): Record<string, unknown> {
  const core: Record<string, DtcgToken> = {};
  for (const [name, style] of Object.entries(data.type)) {
    core[name] = typography(style);
  }
  for (const [name, value] of Object.entries({
    ...data.spacing,
    ...data.size,
  })) {
    // Fluid spacing is in vw, which DTCG dimensions don't allow.
    if (DIMENSION.test(dimension(value))) {
      core[name] = { $type: "dimension", $value: dimension(value) };
    }
  }

  const sets: Record<string, Record<string, DtcgToken>> = { core };
  for (const theme of THEMES) {
    sets[theme] = Object.fromEntries(
      Object.entries({ ...data.color, ...data.component }).map(
        ([name, values]) => [
          name,
          { $type: "color", $value: colorValue(values[theme]) },
        ],
      ),
    );
  }

  return {
    ...sets,
    $themes: THEMES.map((theme) => ({
      id: theme,
      name: THEME_NAMES[theme],
      selectedTokenSets: { core: "enabled", [theme]: "enabled" },
    })),
    $metadata: { tokenSetOrder: Object.keys(sets) },
  };
}

export function renderDtcg(data: TokenData): string {
  return `${JSON.stringify(dtcgTokens(data), null, 2)}\n`;
}
