import { render, screen } from "@testing-library/svelte";
import { user } from "../utils/user";
import AILabelTest from "./AILabel.test.svelte";
import AILabelActions from "./AILabelActions.test.svelte";

describe("AILabel", () => {
  it("names the button with the AI text and description", () => {
    render(AILabelTest);
    const button = screen.getByRole("button", { name: "AI Show information" });
    expect(button).toHaveTextContent("AI");
    expect(screen.getByTestId("label")).toHaveClass("bx--ai-label--xs");
  });

  it("applies the size and inline classes", () => {
    render(AILabelTest, { props: { size: "md", kind: "inline" } });
    const label = screen.getByTestId("label");
    expect(label).toHaveClass("bx--ai-label--md", "bx--ai-label--inline");
    expect(label).not.toHaveClass("bx--ai-label--inline-with-content");
  });

  it("shows textLabel after the AI text inline, and names the button with it", () => {
    render(AILabelTest, {
      props: { kind: "inline", textLabel: "Text goes here" },
    });
    expect(screen.getByTestId("label")).toHaveClass(
      "bx--ai-label--inline-with-content",
    );
    expect(
      screen.getByRole("button", { name: "AI Text goes here" }),
    ).toHaveTextContent("AI Text goes here");
  });

  it("opens the AI callout, not the high-contrast popover", async () => {
    render(AILabelTest);
    await user.click(
      screen.getByRole("button", { name: "AI Show information" }),
    );
    const content = screen.getByText("Generated by a model.");
    const popover = content.closest(".bx--popover");
    expect(popover).toHaveClass("bx--ai-label-popover", "bx--popover--open");
    expect(popover).not.toHaveClass("bx--popover--high-contrast");
  });

  it("keeps a Toggletip inside the callout a plain toggletip", async () => {
    render(AILabelTest);
    await user.click(
      screen.getByRole("button", { name: "AI Show information" }),
    );
    await user.click(screen.getByRole("button", { name: "Nested" }));
    const nested = screen.getByText("Nested content").closest(".bx--popover");
    expect(nested).toHaveClass("bx--popover--high-contrast");
    expect(nested).not.toHaveClass("bx--ai-label-popover");
  });

  it("renders the actions bar only with actions", () => {
    const { container } = render(AILabelTest);
    expect(container.querySelector(".bx--ai-label-actions")).toBeNull();
    const actions = render(AILabelActions).container;
    expect(actions.querySelector(".bx--ai-label-actions")).toHaveTextContent(
      "View details",
    );
    expect(actions.querySelector(".bx--ai-label-content")).toHaveClass(
      "bx--ai-label-content--with-actions",
    );
  });

  it("replaces the label with a revert button that dispatches revert", async () => {
    const onrevert = vi.fn();
    render(AILabelTest, { props: { revertActive: true, onrevert } });
    expect(
      screen.queryByRole("button", { name: "AI Show information" }),
    ).not.toBeInTheDocument();
    await user.click(
      screen.getByRole("button", { name: "Revert to AI input" }),
    );
    expect(onrevert).toHaveBeenCalledOnce();
    expect(screen.getByTestId("label")).toHaveClass("bx--ai-label--revert");
  });
});
